// Token Radar's model, radar-2: one snapshot of the protocol universe in, one ranked board out.
//
// The board ranks every protocol the snapshot records as pre-token and not a wrapped, staked or
// bridged product of a token that already trades: the snapshot's 40-protocol watchlist is the floor,
// and every other protocol that passes the same rule joins it, however small its TVL. Nothing is
// capped by TVL and no name is ever special-cased, so a future snapshot with new protocols scores
// them the same way: the radar finds launches early because it reads the rule, not a list.
//
// A protocol is pre-token when its record carries no token at all (no market cap, no CoinGecko id,
// no symbol). It is excluded from the early radar when it is a wrapped, staked or bridged product:
// its category is Bridge, Canonical Bridge, Liquid Staking, Liquid Restaking, Restaked BTC or CEX,
// its name carries a whole word wrapped, staked or staking, it begins with an exchange's name, or
// it ends in a version marker. The watchlist rows are kept as the snapshot names them.
//
// Implied value follows only from the snapshot's own figures, in four factors:
//
//   category multiple = median(mcap_usd / tvl_usd) over the live-token protocols of the same
//                       category (at least 3 of them, else the global median), clamped to
//                       [0.05, 1.00]. This is what the market already pays per dollar of TVL for
//                       this kind of protocol: a lending protocol is priced like lending, not like
//                       a bridge. It is computed from the snapshot at run time, never looked up.
//   base              = tvl_usd x category multiple
//   growth            = 1 + clamp(change_7d, -60, 120) / 100 x 0.5
//   maturity          = 0.6 + min(age_days, 1095) / 1095 x 0.4   (age unknown: 365 days)
//   breadth           = 1 + min(chains - 1, 5) x 0.02   (a protocol live on more chains)
//   implied           = max(1, round(base x growth x maturity x breadth))
//
// The dashboard recomputes the same four factors from the same figures and shows them per row, so
// the page's arithmetic and board.json's numbers are visibly the same model.

/** The snapshot's protocol entry: exactly the ten fields the sealed input carries. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

